import { createHash } from 'node:crypto';
import { access, copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, isAbsolute, relative, resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';

const defaultWebRoot = resolve(import.meta.dirname, '..');
const generatedName = 'content-assets.js';

function inside(root, path) {
  const local = relative(root, path);
  return local && !local.startsWith(`..${sep}`) && local !== '..' && !isAbsolute(local);
}

function sourceObject(source, name) {
  const start = source.indexOf(`const ${name}:`);
  if (start < 0) throw new Error(`Mobile asset declaration '${name}' is missing.`);
  const opening = source.indexOf('= {', start);
  const closing = source.indexOf('\n};', opening);
  if (opening < 0 || closing < 0) throw new Error(`Mobile asset declaration '${name}' cannot be read.`);
  return source.slice(opening + 3, closing).replace(/\r/g, '');
}

function declaredEntries(source, expression, label) {
  const entries = [...source.matchAll(expression)];
  const remainder = source.replace(expression, '').replace(/\/\/[^\n]*/g, '').trim();
  if (remainder || !entries.length) throw new Error(`Unsupported ${label} declaration; update the admin asset synchronizer.`);
  return entries;
}

export async function readMobileContent(mobileRoot) {
  const foodSource = resolve(mobileRoot, 'src/food');
  const [photography, images] = await Promise.all([
    readFile(resolve(foodSource, 'foodPhotography.ts'), 'utf8'),
    readFile(resolve(foodSource, 'assets.ts'), 'utf8'),
  ]);
  const photographs = new Map();
  const photoEntries = declaredEntries(sourceObject(photography, 'photos'), /^\s*['"]([^'"]+)['"]\s*:\s*\{([^{}]*)\}\s*,?\s*$/gm, 'photograph');
  for (const [, key, fields] of photoEntries) {
    const asset = fields.match(/source:\s*require\(['"]([^'"]+)['"]\)/)?.[1];
    const width = Number(fields.match(/\bwidth:\s*(\d+)/)?.[1]);
    const height = Number(fields.match(/\bheight:\s*(\d+)/)?.[1]);
    const cropText = fields.match(/\bcrop:\s*\[([^\]]+)\]/)?.[1];
    const crop = cropText?.split(',').map(value => Number(value.trim()));
    const fit = fields.match(/\bfit:\s*['"]([^'"]+)['"]/)?.[1];
    if (!asset || !width || !height || (crop && (crop.length !== 4 || crop.some(value => !Number.isFinite(value)))) || (fit && fit !== 'contain')) {
      throw new Error(`Invalid photograph metadata for '${key}'.`);
    }
    photographs.set(key, { file: resolve(foodSource, asset), kind: 'photograph', width, height, ...(crop ? { crop } : {}), ...(fit ? { fit } : {}) });
  }
  const aliases = declaredEntries(sourceObject(photography, 'aliases'), /^\s*['"]([^'"]+)['"]\s*:\s*['"]([^'"]+)['"]\s*,?\s*$/gm, 'photograph alias');
  for (const [, key, target] of aliases) {
    if (!photographs.has(target)) throw new Error(`Unknown photograph alias '${target}'.`);
    photographs.set(key, photographs.get(target));
  }
  const bundled = declaredEntries(sourceObject(images, 'images'), /^\s*(?:['"]([^'"]+)['"]|([\w-]+))\s*:\s*require\(['"]([^'"]+)['"]\)\s*,?\s*$/gm, 'bundled image');
  const result = new Map(photographs);
  for (const [, quotedKey, plainKey, asset] of bundled) {
    const key = quotedKey || plainKey;
    if (!result.has(key)) result.set(key, { file: resolve(foodSource, asset), kind: 'bundled' });
  }
  for (const [key, asset] of result) {
    if (!inside(mobileRoot, asset.file) || !/\.(png|jpe?g|webp)$/i.test(asset.file)) throw new Error(`Unsafe mobile asset path for '${key}'.`);
    await access(asset.file);
  }
  return result;
}

export function manifestModule(assets) {
  return `// Generated by web/scripts/sync-admin-content.mjs from the current mobile image catalog.\n// Keep this module and assets/food in standalone website release bundles.\nexport const contentAssets = ${JSON.stringify(assets, null, 2)};\n\n// Mobile photography takes priority for both the key and its fallback.\nexport function resolveContentAsset(key, fallbackKey = '') {\n  const primary = contentAssets[key || ''];\n  const fallback = contentAssets[fallbackKey || ''];\n  if (primary?.kind === 'photograph') return primary;\n  if (fallback?.kind === 'photograph') return fallback;\n  return primary || fallback;\n}\n`;
}

async function fileHash(file) {
  return createHash('sha256').update(await readFile(file)).digest('hex');
}

export async function validateStagedContent(adminRoot) {
  const manifest = await readFile(resolve(adminRoot, generatedName), 'utf8');
  const serialized = manifest.match(/export const contentAssets = (\{[\s\S]*?\n\});/)?.[1];
  if (!serialized) throw new Error('The staged admin image manifest is missing or invalid.');
  const assets = JSON.parse(serialized);
  if (!Object.keys(assets).length) throw new Error('The staged admin image manifest is empty.');
  const verified = new Set();
  for (const [key, asset] of Object.entries(assets)) {
    if (typeof asset.src !== 'string' || !asset.src.startsWith('./assets/food/') || !/^[a-f0-9]{64}$/.test(asset.sha256)) throw new Error(`Invalid staged image '${key}'.`);
    const file = resolve(adminRoot, asset.src);
    if (!inside(adminRoot, file)) throw new Error(`Unsafe staged image path for '${key}'.`);
    if (!verified.has(file)) {
      if (await fileHash(file) !== asset.sha256) throw new Error(`Staged admin image '${key}' is missing or changed.`);
      verified.add(file);
    }
  }
  return { keys: Object.keys(assets).length, files: verified.size, assets };
}

export async function syncAdminContent({ webRoot = defaultWebRoot, mobileRoot = resolve(webRoot, '../mobile'), check = false } = {}) {
  const adminRoot = resolve(webRoot, 'admin/dist');
  // Railway builds the website with its own context, without the mobile tree.
  // Validate the checked-in snapshot rather than silently regenerating old photos.
  try { await access(mobileRoot); } catch {
    const staged = await validateStagedContent(adminRoot);
    return { ...staged, staged: true };
  }
  const sourceAssets = await readMobileContent(mobileRoot);
  const assets = {};
  const files = new Map();
  for (const [key, { file, ...metadata }] of [...sourceAssets].sort(([a], [b]) => a.localeCompare(b, 'en'))) {
    const folder = metadata.kind === 'photograph' ? 'real' : 'legacy';
    const src = `./assets/food/${folder}/${basename(file)}`;
    const destination = resolve(adminRoot, src);
    if (files.has(destination) && files.get(destination) !== file) throw new Error(`Duplicate admin image filename '${src}'.`);
    files.set(destination, file);
    assets[key] = { src, ...metadata, sha256: await fileHash(file) };
  }
  const expected = manifestModule(assets);
  if (check) {
    if (await readFile(resolve(adminRoot, generatedName), 'utf8') !== expected) throw new Error('Admin image manifest does not match the current mobile catalog. Run npm run sync:admin-content in web.');
  } else {
    for (const [destination, source] of files) {
      await mkdir(dirname(destination), { recursive: true });
      await copyFile(source, destination);
    }
    await writeFile(resolve(adminRoot, generatedName), expected, 'utf8');
  }
  return { ...(await validateStagedContent(adminRoot)), staged: false };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const result = await syncAdminContent({ check: process.argv.includes('--check') });
  console.log(`Admin content: ${result.keys} image keys, ${result.files} verified files${result.staged ? ' (standalone snapshot)' : ''}.`);
}
